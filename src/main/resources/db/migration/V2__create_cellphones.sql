CREATE TABLE IF NOT EXISTS cellphones (
    id                  VARCHAR(36)  NOT NULL PRIMARY KEY,
    brand               VARCHAR(100) NOT NULL,
    imei                VARCHAR(15)  NOT NULL,
    screen_size         DECIMAL(6,2) NOT NULL,
    megapixels          DECIMAL(7,2) NOT NULL,
    ram                 INT NOT NULL,
    primary_storage     INT NOT NULL,
    secondary_storage   INT NULL,
    operating_system    VARCHAR(100) NOT NULL,
    operator_name       VARCHAR(100) NOT NULL,
    band_technology     VARCHAR(100) NOT NULL,
    wifi                BOOLEAN NOT NULL,
    bluetooth           BOOLEAN NOT NULL,
    cameras             INT NOT NULL,
    cpu_brand           VARCHAR(100) NOT NULL,
    cpu_speed           DECIMAL(6,2) NOT NULL,
    nfc                 BOOLEAN NOT NULL,
    fingerprint         BOOLEAN NOT NULL,
    infrared            BOOLEAN NOT NULL,
    water_resistant     BOOLEAN NOT NULL,
    sim_count           INT NOT NULL,
    CONSTRAINT uq_cellphones_imei UNIQUE (imei)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
